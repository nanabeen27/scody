import type { ContentSet, Question } from './types';

/**
 * 문법형 문항 은행.
 *
 * 항목(정답 1개 + 오답 3개)은 손으로 정리한 실제 어법 자료다.
 * 문항 객체만 인덱스로 조립해 세트당 20문항 이상을 만든다. 난수·현재 시각을 쓰지 않는다.
 */
interface Item {
  /** 정답 보기 */
  ok: string;
  /** 오답 보기 3개 */
  no: [string, string, string];
  why: string;
}

function build(id: string, prompt: string, items: readonly Item[]): Question[] {
  return items.map((item, i) => {
    // 정답 위치를 문항마다 돌려 한 자리에 몰리지 않게 한다.
    const answerIndex = i % 4;
    const choices = [...item.no];
    choices.splice(answerIndex, 0, item.ok);
    return {
      id: `${id}_q${i + 1}`,
      prompt,
      choices,
      answerIndex,
      explanation: item.why,
    };
  });
}

