/**
 * 한 오답의 문항 정보. AI에게 넘길 컨텍스트다.
 *
 * `pickedLabel`만 화면마다 다르다 — 오답노트는 방금 푼 결과를 보고 있어 `내가 고른 답`,
 * 카드 복습은 다시 푸는 자리라 `지난번 내 답`이다.
 */
export function wrongCtx(n: WrongNoteContext, pickedLabel = '내가 고른 답'): string {
  const picked = n.pickedIndex != null ? n.choices[n.pickedIndex] : '없음';
  return `문제: ${n.prompt}\n보기: ${n.choices.join(' / ')}\n정답: ${n.choices[n.answerIndex]}\n${pickedLabel}: ${picked}`;
}

/** `wrongCtx`가 실제로 읽는 것만. `WrongNote` 전체를 요구하지 않는다. */
export interface WrongNoteContext {
  prompt: string;
  choices: readonly string[];
  answerIndex: number;
  pickedIndex?: number;
}
