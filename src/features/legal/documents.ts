export type LegalSlug = 'about' | 'terms' | 'privacy' | 'business';

export interface LegalBlock {
  heading?: string;
  /** 문단. 한 줄에 한 가지만 담는다. */
  paragraphs?: string[];
  /** 목록. 앞에 가운뎃점을 붙여 보여준다. */
  items?: string[];
  /** 라벨-값 목록(사업자정보처럼 항목이 정해진 문서용). */
  rows?: { label: string; value: string }[];
}

export interface LegalDoc {
  slug: LegalSlug;
  /** 푸터에 노출하는 이름. */
  label: string;
  title: string;
  /** 제목 위 한 줄. 문서 성격을 먼저 밝힌다. */
  eyebrow: string;
  /** 문서 맨 위 안내(초안 여부 등). */
  notice?: string;
  blocks: LegalBlock[];
}

